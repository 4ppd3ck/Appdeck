//go:build darwin

// macOS privilege mapping: a privileged app launches from its OWN generated
// .app bundle so TCC (Full Disk Access & friends) attributes to that app's
// identity instead of the launcher's — AppDeck itself never needs a grant,
// and no sibling app can ride one. The bundle's executable is a tiny sh shim
// that sources a launcher-written env file (Launch Services launches carry no
// launcher environment), appends output to the app's regular log, and execs
// the real binary on the same PID (keeping TCC attribution on the bundle).
//
// Bundles are signed with a stable self-signed identity ("AppDeck App
// Wrapper") created once in the login keychain: TCC pins grants to the
// signing identity + bundle ID, so grants survive rebuilds and arch changes.
// When the identity cannot be created the bundles sign ad-hoc — everything
// works, but macOS re-asks for each grant after every rebuild.
//
// SECURITY: that identity is equivalent to "may inherit every privileged
// app's grants" — anything signed with it AND a matching bundle ID inherits
// the grant. Keep the key's keychain ACL limited to codesign (the default on
// import) and never export it.
package main

import (
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"time"
)

// The launcher icon is the fallback for apps without a raster icon.
//
//go:embed AppDeck.icns
var defaultTccIcon []byte

const (
	tccIdentityName   = "AppDeck App Wrapper"
	tccBundleIDPrefix = "com.appdeck."
)

// tccShimScript builds the bundle executable: source the start-specific env,
// append the app's output to its regular log, then exec the real binary in
// this same process so TCC responsibility stays with the bundle.
func tccShimScript(envFile, realBinary, logPath string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# AppDeck per-app TCC wrapper — regenerated by the launcher; do not edit.\n")
	fmt.Fprintf(&b, ". %q\n", envFile)
	fmt.Fprintf(&b, "exec %q \"$@\" >> %q 2>&1 < /dev/null\n", realBinary, logPath)
	return b.String()
}

// shEnvFile renders childEnv entries as a `.`-sourcable exports file. Values
// are single-quoted with the one escape POSIX sh needs ('\”).
func shEnvFile(env []string) string {
	var b strings.Builder
	for _, kv := range env {
		eq := strings.Index(kv, "=")
		if eq <= 0 {
			continue
		}
		k, v := kv[:eq], kv[eq+1:]
		fmt.Fprintf(&b, "export %s='%s'\n", k, strings.ReplaceAll(v, "'", `'\''`))
	}
	return b.String()
}

// tccInfoPlist renders the bundle's Info.plist. LSUIElement keeps faceless
// web/CLI apps off the Dock; GUI desktop apps show properly.
func tccInfoPlist(id, name string, gui bool, version, iconFile string) string {
	if version == "" {
		version = "1"
	}
	ui := "true"
	if gui {
		ui = "false"
	}
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>%s</string>
  <key>CFBundleIdentifier</key><string>%s%s</string>
  <key>CFBundleName</key><string>%s</string>
  <key>CFBundleDisplayName</key><string>%s</string>
  <key>CFBundleShortVersionString</key><string>%s</string>
  <key>CFBundleVersion</key><string>%s</string>
  <key>CFBundleIconFile</key><string>%s</string>
  <key>LSUIElement</key><%s/>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
`, id, tccBundleIDPrefix, id, plistEscape(name), plistEscape(name), plistEscape(version), plistEscape(version), iconFile, ui)
}

func plistEscape(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;")
	return r.Replace(s)
}

// ensureSigningIdentity returns the codesign identity (a keychain SHA-1
// hash) to sign bundles with, creating the one-time self-signed
// "AppDeck App Wrapper" certificate in the login keychain on first use.
// Falls back to ad-hoc ("-") when anything in the keychain flow declines or
// fails — launch still works, grants just re-prompt after rebuilds.
func ensureSigningIdentity() string {
	if id := findSigningIdentity(); id != "" {
		return id
	}
	tmp, err := os.MkdirTemp("", "appdeck-identity-")
	if err != nil {
		return "-"
	}
	defer os.RemoveAll(tmp)
	key := filepath.Join(tmp, "key.pem")
	cert := filepath.Join(tmp, "cert.pem")
	cnf := filepath.Join(tmp, "ext.cnf")
	p12 := filepath.Join(tmp, "id.p12")
	if err := os.WriteFile(cnf, []byte(
		"[req]\ndistinguished_name=dn\nx509_extensions=v3\nprompt=no\n[dn]\nCN="+tccIdentityName+"\nO=AppDeck\n"+
			"[v3]\nkeyUsage=digitalSignature\nextendedKeyUsage=codeSigning\nbasicConstraints=critical,CA:FALSE\n"), 0o644); err != nil {
		return "-"
	}
	// /usr/bin/openssl is LibreSSL on macOS — no -addext, so the extension
	// config above carries the codeSigning EKU instead.
	if out, err := exec.Command("/usr/bin/openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes",
		"-days", "3650", "-keyout", key, "-out", cert, "-config", cnf).CombinedOutput(); err != nil {
		_ = out
		return "-"
	}
	if out, err := exec.Command("/usr/bin/openssl", "pkcs12", "-export",
		"-out", p12, "-inkey", key, "-in", cert, "-passout", "pass:appdeck-tmp").CombinedOutput(); err != nil {
		_ = out
		return "-"
	}
	keychain := filepath.Join(os.Getenv("HOME"), "Library", "Keychains", "login.keychain-db")
	// -T lets codesign use the key without a per-signing prompt; the key
	// stays ACL-restricted to codesign (the identity-is-grant rule above).
	if out, err := exec.Command("/usr/bin/security", "import", p12,
		"-k", keychain, "-T", "/usr/bin/codesign", "-P", "appdeck-tmp").CombinedOutput(); err != nil {
		_ = out
		return "-"
	}
	if id := findSigningIdentity(); id != "" {
		return id
	}
	return "-"
}

// findSigningIdentity returns the SHA-1 hash of the wrapper identity, or "".
// The non-verbose listing is required: self-signed identities are always
// "NOT TRUSTED" (trust is for verification, not signing), which -v hides.
// The hash — not the name — is what codesign -s gets, so duplicate names can
// never make a sign ambiguous.
var identityLineRe = regexp.MustCompile(`^\s*\d+\)\s+([0-9A-Fa-f]{40})\s+"` + tccIdentityName + `"`)

func findSigningIdentity() string {
	out, err := exec.Command("/usr/bin/security", "find-identity", "-p", "codesigning").Output()
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(out), "\n") {
		if m := identityLineRe.FindStringSubmatch(line); m != nil {
			return m[1]
		}
	}
	return ""
}

// ensureTccBundle builds (and signs) the per-app .app bundle inside the app's
// own folder, unless the current one already matches. Returns the bundle path
// and whether the signing identity is stable (non ad-hoc).
func (s *Server) ensureTccBundle(a *App, envFile, realBinary string) (string, error) {
	// The identity is resolved before the stamp check: if it was deleted and
	// re-created (Keychain cleanup, expired cert), the hash below changes and
	// every bundle re-signs onto the new identity on its next start.
	identity := ensureSigningIdentity()
	bundle := filepath.Join(a.Dir, slugify(a.ID)+".app")
	contents := filepath.Join(bundle, "Contents", "MacOS")
	resources := filepath.Join(bundle, "Contents", "Resources")
	if err := os.MkdirAll(contents, 0o755); err != nil {
		return "", err
	}
	_ = os.MkdirAll(resources, 0o755)

	shim := tccShimScript(envFile, realBinary, s.logPath(a))
	iconName, iconData := tccBundleIcon(a)
	plist := tccInfoPlist(slugify(a.ID), a.Name, a.Desktop, a.Version, iconName)
	// The stamp lives NEXT to the bundle, never inside it: anything in
	// Contents/ that is not a standard bundle member breaks the seal
	// ("unsealed contents") on every later codesign pass.
	stampPath := bundle + ".stamp"
	iconHash := sha256.Sum256(iconData)
	want := sha256.Sum256([]byte(shim + "\x00" + plist + "\x00" + fileStamp(realBinary) + "\x00" + identity + "\x00" + hex.EncodeToString(iconHash[:])))
	if old, err := os.ReadFile(stampPath); err == nil && hex.EncodeToString(want[:]) == strings.TrimSpace(string(old)) {
		return bundle, nil // unchanged since the last sign
	}
	if err := os.WriteFile(filepath.Join(contents, slugify(a.ID)), []byte(shim), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(bundle, "Contents", "Info.plist"), []byte(plist), 0o644); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(resources, iconName+".icns"), iconData, 0o644); err != nil {
		return "", err
	}
	for _, stale := range []string{"AppDeck.icns", "AppIcon.icns"} {
		if stale != iconName+".icns" {
			_ = os.Remove(filepath.Join(resources, stale))
		}
	}
	sign := exec.Command("/usr/bin/codesign", "--force", "-s", identity, bundle)
	if out, err := sign.CombinedOutput(); err != nil {
		// A signature failure must never brick the launch: retry ad-hoc,
		// which always succeeds and still gives the bundle its own identity.
		adHoc := exec.Command("/usr/bin/codesign", "--force", "-s", "-", bundle)
		if out2, err2 := adHoc.CombinedOutput(); err2 != nil {
			return "", fmt.Errorf("codesign: %v / %v: %s %s", err, err2, lastN(string(out), 200), lastN(string(out2), 200))
		}
	}
	_ = os.WriteFile(stampPath, []byte(hex.EncodeToString(want[:])+"\n"), 0o644)
	return bundle, nil
}

// tccBundleIcon converts a PNG app-folder icon to the ICNS format Launch
// Services expects. Missing, SVG, or unsupported artwork uses AppDeck's icon.
func tccBundleIcon(a *App) (string, []byte) {
	data, ctype, ok := appIcon(a)
	if ok && ctype == "image/png" {
		tmp, err := os.MkdirTemp("", "appdeck-icon-")
		if err == nil {
			defer os.RemoveAll(tmp)
			source := filepath.Join(tmp, "icon.png")
			target := filepath.Join(tmp, "icon.icns")
			if err := os.WriteFile(source, data, 0o600); err == nil {
				if out, err := exec.Command("/usr/bin/sips", "-s", "format", "icns", source, "--out", target).CombinedOutput(); err == nil {
					if icon, err := os.ReadFile(target); err == nil {
						return "AppIcon", icon
					}
				} else {
					_ = out
				}
			}
		}
	}
	return "AppDeck", defaultTccIcon
}

func fileStamp(path string) string {
	st, err := os.Stat(path)
	if err != nil {
		return ""
	}
	return fmt.Sprintf("%d:%d", st.Size(), st.ModTime().UnixNano())
}

func lastN(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[len(s)-n:]
}

// launchTccApp performs a privileged start: write this start's environment,
// make sure the bundle exists and is signed, hand it to Launch Services
// (open -n -W — the -W exit feeds keepAlive like cmd.Wait does), then find
// the real binary's PID (open is async; the shim execs the binary into the
// same process, so pgrep on the binary path finds the app itself).
func (s *Server) launchTccApp(a *App, env []string, args []string) (int, chan struct{}, error) {
	appData := s.appDataDir(a)
	envFile := filepath.Join(appData, "launch.env")
	if err := os.WriteFile(envFile, []byte(shEnvFile(env)), 0o644); err != nil {
		return 0, nil, fmt.Errorf("writing launch.env: %v", err)
	}
	realBinary, err := s.resolveAppBinary(a)
	if err != nil {
		return 0, nil, err
	}
	bundle, err := s.ensureTccBundle(a, envFile, realBinary)
	if err != nil {
		return 0, nil, fmt.Errorf("preparing the app's macOS bundle: %v", err)
	}

	// --args is what puts the app's arguments in the launched process's argv;
	// without it open parses them as its own options ("--port" →
	// "unrecognized option") and nothing launches at all.
	openArgs := append([]string{"-n", "-W", bundle, "--args"}, args...)
	exited := make(chan struct{})
	var openMu sync.Mutex
	var openFail string
	go func() {
		cmd := exec.Command("/usr/bin/open", openArgs...)
		hideWindow(cmd)
		out, err := cmd.CombinedOutput()
		if err != nil {
			// open's own diagnostic (e.g. "unrecognized option") is the only
			// explanation when no process ever appears — keep it for the error.
			openMu.Lock()
			openFail = lastN(strings.TrimSpace(string(out)), 300)
			if openFail == "" {
				openFail = err.Error()
			}
			openMu.Unlock()
		}
		close(exited)
	}()

	pid := 0
	deadline := time.Now().Add(10 * time.Second)
	// The pattern is anchored to the binary's own argv slot: unanchored, a
	// plain binary name ("…/Apps/descale/descale") also substring-matches the
	// open helper's cmdline ("…/Apps/descale/descale.app --args …") and the
	// recorded PID becomes the launcher's own child — stopping the app then
	// group-kills AppDeck itself.
	pattern := regexp.QuoteMeta(realBinary) + `( |$)`
	for time.Now().Before(deadline) {
		if out, err := exec.Command("/usr/bin/pgrep", "-f", pattern).Output(); err == nil {
			if p := parseFirstPID(string(out)); p != 0 {
				pid = p
				break
			}
		}
		// open already gave up with a diagnostic: no poll will find a process
		// it refused to launch — report now instead of spinning the window.
		select {
		case <-exited:
			openMu.Lock()
			fail := openFail
			openMu.Unlock()
			if fail != "" {
				return 0, exited, fmt.Errorf("could not launch %s: %s", bundle, fail)
			}
		default:
		}
		time.Sleep(250 * time.Millisecond)
	}
	if pid == 0 {
		return 0, exited, fmt.Errorf("launched %s but could not find its process — check the app log", bundle)
	}
	return pid, exited, nil
}

func parseFirstPID(out string) int {
	for _, line := range strings.Fields(out) {
		var pid int
		if _, err := fmt.Sscanf(line, "%d", &pid); err == nil && pid > 1 {
			return pid
		}
	}
	return 0
}

// resetTccGrants drops the app's TCC grants on uninstall so permissions die
// with the app instead of orphaning in the TCC database.
func resetTccGrants(id string) {
	cmd := exec.Command("/usr/bin/tccutil", "reset", "All", tccBundleIDPrefix+slugify(id))
	hideWindow(cmd)
	_, _ = cmd.CombinedOutput()
}

// openFullDiskAccessPane deep-links to System Settings' Full Disk Access
// pane, where the generated bundle must be granted access once.
func openFullDiskAccessPane() {
	cmd := exec.Command("/usr/bin/open", "x-apple.systempreferences:com.apple.preference.security?Privacy_AllFiles")
	hideWindow(cmd)
	_ = cmd.Run()
}
