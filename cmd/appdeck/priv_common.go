// privilegedStartNote is the toast after a privilege toggle: each OS asks
// for the elevation in its own way, so each gets its own "what happens
// next". The privacy class names the macOS pane the one-time grant lives
// in (ignored off darwin — admin/root covers every category there).
func privilegedStartNote(enabled bool, privacy string) string {
	if !enabled {
		return "app launches Inherited — under the launcher's identity again (applies at next start)"
	}
	switch runtime.GOOS {
	case "windows":
		return "app launches as administrator — Windows shows the UAC prompt at every start (applies at next start)"
	case "linux":
		return "app launches as root — the desktop's authorization prompt (pkexec, or sudo with NOPASSWD) appears at every start (applies at next start)"
	default: // darwin
		return "app launches Elevated — its own macOS identity; add its .app under System Settings ▸ Privacy & Security ▸ " + privacyName(privacy) + " once (applies at next start)"
	}
}

// privilegedLaunchNote is the toast after a privileged desktop app start.
func privilegedLaunchNote(privacy string) string {
	switch runtime.GOOS {
	case "windows":
		return "launched as administrator (UAC prompt approved) — Stop asks for the UAC prompt again, an admin child cannot be killed otherwise"
	case "linux":
		return "launched as root via pkexec/sudo — Stop asks for the root prompt again, a root child cannot be killed otherwise"
	default: // darwin
		return "launched with its own macOS identity — add its .app under Privacy & Security ▸ " + privacyName(privacy) + " if it needs that (macOS never asks)"
	}
}

// psSingleQuoted renders a PowerShell single-quoted literal: inside single
// quotes every character is literal except the quote itself, which doubles.
func psSingleQuoted(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// windowsArgToken renders one argument as a Windows command-line token —
// double quotes with backslash-doubling, the rules CommandLineToArgvW
// applies. Start-Process -ArgumentList joins its items with plain spaces on
// Windows PowerShell 5.1 (what both the outer and the elevated process run)
// without quoting them, so tokens must arrive pre-quoted. Single quotes are
// NOT argument quotes on Windows — only double quotes count.
func windowsArgToken(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	run := 0 // backslashes held back: their meaning depends on what follows
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '\\':
			run++
		case '"':
			// 2n+1 backslashes before a quote make it literal; n would
			// terminate the token instead.
			b.WriteString(strings.Repeat(`\`, run*2+1))
			b.WriteByte('"')
			run = 0
		default:
			b.WriteString(strings.Repeat(`\`, run))
			b.WriteByte(c)
			run = 0
		}
	}
	b.WriteString(strings.Repeat(`\`, run*2)) // trailing backslashes double
	b.WriteByte('"')
	return b.String()
}

// adminLaunchScript renders the per-start elevated PowerShell a Windows
// privileged app runs through: set the child environment, start the real
// binary with its output going to the app's log files, publish its PID for
// the launcher, then stay alive until the app exits — the launcher's exited
// channel hangs off the outer elevation process that waits for this script
// (see priv_windows.go).
//
// Two Start-Process redirect constraints shape the log story: the two
// streams cannot share one file (stderr gets the sibling .err that tailLog
// appends for the Logs view), and the targets are created fresh, so the
// script re-writes the regular start marker after the redirect truncates it.
func adminLaunchScript(bin, dir string, args, env []string, logPath, pidPath string, hidden bool) string {
	var b strings.Builder
	b.WriteString("# AppDeck per-app elevation wrapper — regenerated by the launcher on every start; do not edit.\n")
	b.WriteString("$ErrorActionPreference = 'Stop'\n")
	for _, kv := range env {
		eq := strings.Index(kv, "=")
		if eq <= 0 {
			continue
		}
		fmt.Fprintf(&b, "${env:%s} = %s\n", kv[:eq], psSingleQuoted(kv[eq+1:]))
	}
	b.WriteString("try {\n")
	fmt.Fprintf(&b, "  $p = Start-Process -FilePath %s", psSingleQuoted(bin))
	if len(args) > 0 {
		items := make([]string, len(args))
		for i, arg := range args {
			items[i] = psSingleQuoted(windowsArgToken(arg))
		}
		fmt.Fprintf(&b, " -ArgumentList %s", strings.Join(items, ","))
	}
	fmt.Fprintf(&b, " -WorkingDirectory %s -PassThru", psSingleQuoted(dir))
	if hidden {
		b.WriteString(" -WindowStyle Hidden")
	}
	fmt.Fprintf(&b, " -RedirectStandardOutput %s -RedirectStandardError %s\n",
		psSingleQuoted(logPath), psSingleQuoted(logPath+".err"))
	fmt.Fprintf(&b, "  Set-Content -LiteralPath %s -Value $p.Id\n", psSingleQuoted(pidPath))
	fmt.Fprintf(&b, "  Add-Content -LiteralPath %s -Value ('===== started ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + ' =====')\n", psSingleQuoted(logPath))
	b.WriteString("  $p.WaitForExit()\n")
	b.WriteString("  exit $p.ExitCode\n")
	b.WriteString("} catch {\n")
	fmt.Fprintf(&b, "  Add-Content -LiteralPath %s -Value ('appdeck: could not start the app as administrator: ' + $_.Exception.Message + ' (' + %s + ')')\n", psSingleQuoted(logPath), psSingleQuoted(bin))
	b.WriteString("  exit 1\n")
	b.WriteString("}\n")
	return b.String()
}

// Mach-O magic prefixes (both byte orders, plus fat binaries): a macOS
// executable where a Windows one was expected is a common wrong-asset
// import, so it gets its own diagnosis.
var machoMagics = [][]byte{
	{0xFE, 0xED, 0xFA, 0xCE}, {0xFE, 0xED, 0xFA, 0xCF},
	{0xCE, 0xFA, 0xED, 0xFE}, {0xCF, 0xFA, 0xED, 0xFE},
	{0xCA, 0xFE, 0xBA, 0xBE}, {0xBE, 0xBA, 0xFE, 0xCA},
}

// PE machine types (the COFF header's Machine field) and which ones each
// host architecture can run: x64 natively runs x64 plus WOW64 x86, and
// Windows on ARM64 additionally emulates x64/x86 and runs ARM32 natively.
var peMachineName = map[uint16]string{
	0x8664: "x64",
	0x014c: "32-bit x86",
	0xaa64: "ARM64",
	0x01c4: "32-bit ARM",
	0x01c0: "32-bit ARM",
	0x0200: "Itanium",
}

var peRunnableOn = map[string]map[uint16]bool{
	"amd64": {0x8664: true, 0x014c: true},
	"arm64": {0xaa64: true, 0x8664: true, 0x014c: true, 0x01c4: true, 0x01c0: true},
	"386":   {0x014c: true},
	"arm":   {0x01c4: true, 0x01c0: true, 0x014c: true},
}

var windowsArchName = map[string]string{
	"amd64": "x64", "arm64": "ARM64", "386": "32-bit x86", "arm": "32-bit ARM",
}

// windowsExeProblem explains why a resolved app binary cannot run on
// Windows, or returns "" when it looks runnable. CreateProcess only accepts
// PE images (MZ…PE) plus .bat/.cmd/.com through cmd.exe — everything else
// dies with the famously opaque "%1 is not a valid Win32 application"
// (error 193), naming neither the file nor the reason. The usual suspects —
// a Linux or macOS build, a script, an unextracted archive, a saved web
// page, an empty file, a wrong-architecture PE — become a diagnosis the
// dashboard can show directly. Anything not confidently classified stays
// runnable: an exotic-but-valid binary must never be blocked by its own
// launcher.
func windowsExeProblem(path string) string {
	switch strings.ToLower(filepath.Ext(path)) {
	case ".bat", ".cmd", ".com":
		return "" // CreateProcess runs these through cmd.exe
	}
	f, err := os.Open(path)
	if err != nil {
		return "" // unreadable now; the real start will surface the error
	}
	defer f.Close()
	head := make([]byte, 512)
	n, _ := f.Read(head)
	head = head[:n]
	for _, m := range machoMagics {
		if bytes.HasPrefix(head, m) {
			return "it is a macOS executable (Mach-O), not a Windows program — import the Windows build"
		}
	}
	switch {
	case len(head) == 0:
		return "the file is empty — a failed download or build"
	case bytes.HasPrefix(head, []byte("\x7fELF")):
		return "it is a Linux executable (ELF), not a Windows program — import the Windows build"
	case bytes.HasPrefix(head, []byte("#!")):
		return "it is a script — Windows cannot run it directly; point the app at an .exe or a .bat/.cmd launcher"
	case bytes.HasPrefix(head, []byte("PK")):
		return "it is still a zip archive, not an extracted executable"
	case bytes.HasPrefix(bytes.TrimLeft(head, " \t\r\n"), []byte("<")):
		return "it looks like a web page, not an executable — a failed download?"
	case len(head) < 2 || head[0] != 'M' || head[1] != 'Z':
		return "it has no Windows executable header"
	}
	// MZ: a real PE carries its signature at the e_lfanew offset (0x3c).
	if len(head) < 0x40 {
		return "it has no PE header — a DOS-era program or a truncated file"
	}
	off := int64(binary.LittleEndian.Uint32(head[0x3c:0x40]))
	var sig []byte
	if off > 0 && off+6 <= int64(len(head)) {
		sig = head[off : off+6]
	} else if _, err := f.Seek(off, io.SeekStart); err == nil {
		buf := make([]byte, 6)
		if m, _ := f.Read(buf); m == 6 {
			sig = buf
		}
	}
	if len(sig) < 6 || string(sig[:4]) != "PE\x00\x00" {
		return "it has no PE header — a DOS-era program or a truncated file"
	}
	machine := binary.LittleEndian.Uint16(sig[4:6])
	if _, known := peMachineName[machine]; !known {
		return "" // unrecognized machine type: let Windows judge
	}
	if runnable, isHost := peRunnableOn[runtime.GOARCH]; !isHost || runnable[machine] {
		return ""
	}
	return fmt.Sprintf("it is a Windows %s executable — this machine is %s",
		peMachineName[machine], windowsArchName[runtime.GOARCH])
}

// uacDeclined reports whether an outer elevation run failed because the
// user said no at the UAC prompt — that is an expected outcome with its own
// message, not a malfunction. The check is English-only: localized Windows
// prints its own wording, which surfaces in the generic error instead.
func uacDeclined(output string) bool {
	o := strings.ToLower(output)
	return strings.Contains(o, "canceled by the user") ||
		strings.Contains(o, "cancelled by the user")
}

// sessionEnvVars are the display/session variables a root GUI app needs to
// reach the launching user's session — the ones pkexec's environment scrub
// would otherwise drop (sudo's env_reset does the same).
var sessionEnvVars = []string{
	"DISPLAY", "WAYLAND_DISPLAY", "XAUTHORITY", "XDG_RUNTIME_DIR",
	"XDG_SESSION_TYPE", "DBUS_SESSION_BUS_ADDRESS",
}

// elevatedUnixArgs composes the argv a Linux privileged start executes
// under pkexec or sudo: those scrub the environment, so the child env rides
// through env(1) with the session variables forwarded on top. env(1) leads
// because neither tool accepts VAR=value assignments as its command — pkexec
// would try to run them as the program — and the absolute path survives
// pkexec's secure_path lookup. With a working directory, the app is exec'd
// through a tiny shell that cds first (pkexec does not keep the caller's
// cwd) — the arguments stay separate argv entries, nothing is ever
// interpolated into the shell snippet.
func elevatedUnixArgs(env []string, bin string, args []string, dir string) []string {
	argv := make([]string, 0, len(env)+len(args)+9)
	argv = append(argv, "/usr/bin/env")
	seen := map[string]bool{}
	for _, kv := range env {
		eq := strings.Index(kv, "=")
		if eq <= 0 {
			continue
		}
		argv = append(argv, kv)
		seen[kv[:eq]] = true
	}
	for _, k := range sessionEnvVars {
		if v := os.Getenv(k); v != "" && !seen[k] {
			argv = append(argv, k+"="+v)
		}
	}
	if dir != "" {
		argv = append(argv, "/bin/sh", "-c", `cd "$1" || exit 1; shift; exec "$@"`, "sh", dir)
	}
	argv = append(argv, bin)
	return append(argv, args...)
}

// lastN keeps the tail of s for error surfaces — diagnostics live in the
// app log, the API response only needs the punchline.
func lastN(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[len(s)-n:]
}
